<?php

declare(strict_types=1);

$root = '/home/container';
$file = $root . '/sites.json';
$port = (int) (getenv('SERVER_PORT') ?: 8080);
$defaultPhp = (string) (getenv('PHP_VERSION') ?: '8.3');

$payload = [
    'php_default' => $defaultPhp,
    'port' => $port,
    'sites' => [],
];

if (is_file($file)) {
    $decoded = json_decode((string) file_get_contents($file), true);
    if (is_array($decoded)) {
        $payload = array_merge($payload, $decoded);
        $payload['port'] = $port;
    }
}

function nestcp_abs_root(string $path): string
{
    $path = str_replace('\\', '/', $path);
    $path = ltrim($path, '/');
    if (str_starts_with($path, 'home/container/')) {
        return '/' . $path;
    }
    if (str_starts_with($path, '/home/container/')) {
        return $path;
    }
    return '/home/container/' . $path;
}

function nestcp_proxies(mixed $raw): array
{
    if (!is_array($raw)) {
        return [];
    }
    $out = [];
    foreach ($raw as $row) {
        if (!is_array($row)) {
            continue;
        }
        $path = trim((string) ($row['path'] ?? ''));
        $pass = trim((string) ($row['pass'] ?? $row['upstream'] ?? ''));
        if ($path === '' || $pass === '') {
            continue;
        }
        if ($path[0] !== '/') {
            $path = '/' . $path;
        }
        if (!preg_match('#^/[A-Za-z0-9._\-~/]*$#', $path) || !preg_match('#^https?://[A-Za-z0-9.\-:_\[\]/]+$#', $pass)) {
            continue;
        }
        $out[] = ['path' => $path, 'pass' => $pass];
    }
    return $out;
}

function nestcp_server(string $listen, string $serverName, string $docroot, string $php, string $mode, array $proxies): string
{
    $mode = in_array($mode, ['php', 'spa', 'static'], true) ? $mode : 'php';
    $sock = '/home/container/run/php' . $php . '.sock';
    $try = match ($mode) {
        'spa' => 'try_files $uri $uri/ /index.html;',
        'static' => 'try_files $uri $uri/ =404;',
        default => 'try_files $uri $uri/ /index.php?$query_string;',
    };
    $index = $mode === 'php' ? 'index.php index.html index.htm' : 'index.html index.htm';

    $proxyBlocks = '';
    foreach ($proxies as $proxy) {
        $ssl = '';
        if (str_starts_with($proxy['pass'], 'https://')) {
            $ssl = "\n        proxy_ssl_server_name on;\n        proxy_ssl_name \$host;";
        }
        $proxyBlocks .= <<<NGINX

    location {$proxy['path']} {
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection "upgrade";{$ssl}
        proxy_pass {$proxy['pass']};
    }

NGINX;
    }

    $phpBlock = '';
    if ($mode === 'php') {
        $phpBlock = <<<NGINX

    location ~ \.php$ {
        try_files \$uri =404;
        fastcgi_split_path_info ^(.+\.php)(/.+)$;
        fastcgi_pass unix:{$sock};
        fastcgi_index index.php;
        include /etc/nginx/fastcgi_params;
        fastcgi_param SCRIPT_FILENAME \$document_root\$fastcgi_script_name;
        fastcgi_param PHP_VALUE "upload_max_filesize=100M \n post_max_size=100M";
        fastcgi_read_timeout 300;
    }

NGINX;
    }

    return <<<NGINX
server {
    listen {$listen};
    server_name {$serverName};
    root {$docroot};
    index {$index};
    client_max_body_size 100m;
{$proxyBlocks}
    location / {
        {$try}
    }
{$phpBlock}
    location ~ /\.(?!well-known).* {
        deny all;
    }
}


NGINX;
}

$out = "# Generated by NestCP\n\n";
$yarusDoc = '/home/container/www/yarus/public_html';
$yarusOn = is_file($yarusDoc . '/index.html');
$apiPort = (int) (getenv('YARUS_API_PORT') ?: 3001);
if ($apiPort < 1 || $apiPort > 65535) {
    $apiPort = 3001;
}
$out .= nestcp_server(
    $payload['port'] . ' default_server',
    '_',
    $yarusOn ? $yarusDoc : '/home/container/www/default/public_html',
    (string) $payload['php_default'],
    $yarusOn ? 'spa' : 'php',
    $yarusOn ? [['path' => '/api', 'pass' => 'http://127.0.0.1:' . $apiPort]] : []
);
if ($yarusOn) {
    echo "Yarus site is the default vhost, /api -> 127.0.0.1:{$apiPort}\n";
}

foreach ($payload['sites'] ?? [] as $site) {
    $names = array_merge([(string) ($site['domain'] ?? 'localhost')], $site['aliases'] ?? []);
    $names = array_values(array_unique(array_filter($names)));
    $out .= nestcp_server(
        (string) $payload['port'],
        implode(' ', $names),
        nestcp_abs_root((string) ($site['root'] ?? $site['document_root'] ?? 'www/default/public_html')),
        (string) ($site['php'] ?? $payload['php_default']),
        (string) ($site['index_mode'] ?? 'php'),
        nestcp_proxies($site['proxies'] ?? [])
    );
}

$dir = $root . '/nginx/conf.d';
if (!is_dir($dir)) {
    mkdir($dir, 0755, true);
}
file_put_contents($dir . '/sites.conf', $out);
echo "Rendered nginx sites.conf (" . count($payload['sites'] ?? []) . " sites) on port {$port}\n";
